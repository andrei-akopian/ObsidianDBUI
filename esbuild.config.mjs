import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import path from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
*/
`;

const prod = process.argv[2] === "production";

const testPluginDir = path.resolve("Test/.obsidian/plugins/obsidian-db-ui");

function copyToTestVault() {
  try {
    if (!fs.existsSync(testPluginDir)) {
      fs.mkdirSync(testPluginDir, { recursive: true });
    }
    if (fs.existsSync("main.js")) {
      fs.copyFileSync("main.js", path.join(testPluginDir, "main.js"));
    }
    if (fs.existsSync("manifest.json")) {
      fs.copyFileSync("manifest.json", path.join(testPluginDir, "manifest.json"));
    }
    if (fs.existsSync("styles.css")) {
      fs.copyFileSync("styles.css", path.join(testPluginDir, "styles.css"));
    }
    console.log("Copied plugin build to Test vault plugin directory.");
  } catch (err) {
    console.error("Failed to copy to test vault:", err);
  }
}

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...prod ? [] : []
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: prod,
  outfile: "main.js",
  plugins: [
    {
      name: "copy-to-test-vault",
      setup(build) {
        build.onEnd(() => {
          copyToTestVault();
        });
      },
    },
  ],
});

if (prod) {
  await context.rebuild();
  copyToTestVault();
  process.exit(0);
} else {
  await context.watch();
}
